/// A fake `moon` that replays captured `moon query` output (`<command>.json`
/// next to it), as the extension's `moonBin`. `moon run` records its
/// arguments in `ran.txt`, and fails for targets ending in `:fail`.
#[cfg(unix)]
const FAKE_MOON: &str = "/workspace/fake-moon";
#[cfg(windows)]
const FAKE_MOON: &str = "/workspace/fake-moon.cmd";

fn create_fake_moon(sandbox: &MoonWasmSandbox) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;

        sandbox.create_file(
            "fake-moon",
            "#!/bin/sh\n\
             if [ \"$1\" = run ]; then\n\
             \x20 echo \"$@\" > \"$(dirname \"$0\")/ran.txt\"\n\
             \x20 case \"$2\" in *:fail) exit 3 ;; esac\n\
             \x20 exit 0\n\
             fi\n\
             cat \"$(dirname \"$0\")/$2.json\"\n",
        );

        let path = sandbox.path().join("fake-moon");
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755)).unwrap();
    }

    // A plain `exit` ends cmd.exe with that code; `exit /b` inside a block
    // doesn't reliably set the exit code of a batch file run directly.
    #[cfg(windows)]
    sandbox.create_file(
        "fake-moon.cmd",
        "@if \"%1\"==\"run\" goto run\r\n\
         @type \"%~dp0%2.json\"\r\n\
         @exit /b\r\n\
         :run\r\n\
         @echo %*> \"%~dp0ran.txt\"\r\n\
         @if \"%2\"==\"api:fail\" exit 3\r\n\
         @exit 0\r\n",
    );
}

/// A fake `tilt` for `tilt alpha tiltfile-result`, as the extension's
/// `tiltBin`. It records its arguments in `tilt-ran.txt`, and fails to load
/// (exit code 5, with Tilt's error on stderr) when `load-fails` exists.
#[cfg(unix)]
const FAKE_TILT: &str = "/workspace/fake-tilt";
#[cfg(windows)]
const FAKE_TILT: &str = "/workspace/fake-tilt.cmd";

fn create_fake_tilt(sandbox: &MoonWasmSandbox) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;

        sandbox.create_file(
            "fake-tilt",
            "#!/bin/sh
             dir=\"$(dirname \"$0\")\"
             echo \"$@\" > \"$dir/tilt-ran.txt\"
             if [ -e \"$dir/load-fails\" ]; then
             \x20 echo \"Loading Tiltfile at: $dir/Tiltfile\" >&2
             \x20 echo 'Tiltfile:1:13: k8s_resource specified unknown resource \"api\"' >&2
             \x20 exit 5
             fi
             echo '{\"Manifests\": []}'
",
        );

        let path = sandbox.path().join("fake-tilt");
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755)).unwrap();
    }

    #[cfg(windows)]
    sandbox.create_file(
        "fake-tilt.cmd",
        "@echo %*> \"%~dp0tilt-ran.txt\"\r\n\
         @if exist \"%~dp0load-fails\" goto fail\r\n\
         @echo {\"Manifests\": []}\r\n\
         @exit 0\r\n\
         :fail\r\n\
         @echo Loading Tiltfile at: %~dp0Tiltfile 1>&2\r\n\
         @echo Tiltfile:1:13: k8s_resource specified unknown resource \"api\" 1>&2\r\n\
         @exit 5\r\n",
    );
}

