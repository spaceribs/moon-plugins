        /// Modification time (and, on Unix, inode) of every file under `dir`.
        fn file_identities(dir: &std::path::Path) -> Vec<(std::path::PathBuf, String)> {
            let mut files = vec![];
            let mut pending = vec![dir.to_path_buf()];

            while let Some(dir) = pending.pop() {
                for entry in std::fs::read_dir(dir).unwrap().flatten() {
                    let path = entry.path();
                    let metadata = entry.metadata().unwrap();

                    if metadata.is_dir() {
                        pending.push(path);
                        continue;
                    }

                    #[cfg(unix)]
                    let inode = std::os::unix::fs::MetadataExt::ino(&metadata).to_string();
                    #[cfg(not(unix))]
                    let inode = String::new();

                    files.push((path, format!("{:?} {inode}", metadata.modified().unwrap())));
                }
            }

            files.sort();
            files
        }

